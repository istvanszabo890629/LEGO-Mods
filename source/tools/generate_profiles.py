"""Generate architecture-specific registries from reviewed profiles."""
from pathlib import Path
import argparse
import json
import re
ROOT = Path(__file__).resolve().parents[1]
EXTENDED = {'NuFileExtendedRaw','NuFileExtendedIntrusive','NuFileExtendedShared'}
BACKENDS = {0x14c: {'BatmanVfs','FlatVfs','NuFileDevice','NuFileDeviceSmart','NuFileDeviceSmartCString'} | EXTENDED,
            0x8664: {'NuFileDeviceSmart64','NuFileDeviceSmartCString64','NuFileDeviceShared64','NttFile64'} | EXTENDED}

def hook_literal(hook, image_size, width):
    if hook is None:
        return '{}'
    signature = bytes.fromhex(hook['prologue'])
    relocations = hook['relocations']
    assert len(signature) == 16 and len(relocations) <= 4
    assert len(set(relocations)) == len(relocations)
    assert all(0 <= index < 16 for index in relocations)
    assert 0 < hook['rva'] <= image_size-16-width+1
    values = ','.join(f'0x{value:02X}' for value in signature)
    fields = ','.join(str(value) for value in relocations)
    return f'{{0x{hook["rva"]:X}, {{{{{values}}}}}, {{{{{fields}}}}}, {len(relocations)}}}'

def render(profiles):
    output = ['// Generated by tools/generate_profiles.py; edit profiles.json.\n']
    hashes = set()
    for machine, directive in [(0x8664,'#if defined(_M_X64)'),(0x14c,'#elif defined(_M_IX86)')]:
        output.append(directive+'\n')
        selected = [p for p in profiles if p['machine'] == machine]
        assert selected, f'No profiles for machine {machine:x}'
        for p in selected:
            digest = p['sha256']
            assert re.fullmatch('[0-9a-f]{64}',digest) and digest not in hashes
            hashes.add(digest)
            build, backend = p['build_id'],p['backend']
            assert build in {'None','SteamEnglish','GogEnglish','EpicEnglish','Indy2SteamEnglish','Indy1SteamEnglish','Indy1GogEnglish','Indy2GogEnglish','TcsGogEnglish'}
            assert backend in BACKENDS[machine]
            config = p.get('text_config')
            if config:
                if build=='TcsGogEnglish':
                    assert config=='ENGLISH_PLUS_TCS.ini' and backend=='FlatVfs' and machine==0x14c
                    assert digest=='239f6c09b73e5764ced7469f158b621ff34c9984b5b0a850fe77248add259113'
                elif build in {'Indy1SteamEnglish','Indy1GogEnglish'}:
                    assert config=='ENGLISH_PLUS_IJ1.ini' and backend=='BatmanVfs' and machine==0x14c
                    assert p['sha256']=={'Indy1SteamEnglish':'c12f7348ec63aed61f56eb15d825f15b8340500668fa8c8dcf06c2f332e5e5fd','Indy1GogEnglish':'6c72717abc5b38a44ec235540176c76a2778c1d8f0dd8889b714a12391e162d1'}[build]
                elif build in {'Indy2SteamEnglish','Indy2GogEnglish'}:
                    assert config=='ENGLISH_PLUS_IJ2.ini' and backend=='FlatVfs' and machine==0x14c
                    assert p['sha256']=={'Indy2SteamEnglish':'b3d3a7871187dbb6bd5d357e93a8153585ac68fbe3a302bae7e4ccb372d74ede','Indy2GogEnglish':'1f0f51faf303c446fc21052a10d1cfa1597022f3712f810837119da2af00eb7a'}[build]
                else:
                    assert config == 'ENGLISH_PLUS_LB1.ini' and backend == 'BatmanVfs' and build in {'SteamEnglish','GogEnglish','EpicEnglish'}
            else:
                assert build == 'None'
            assert len(p['hooks']) == 5
            assert all(p['hooks'][:3])
            if backend == 'FlatVfs':
                assert all(p['hooks'][:4]) and p['hooks'][4] is None
            else:
                assert backend in EXTENDED or all(p['hooks'])
            if backend == 'NuFileExtendedShared':
                assert all(p['hooks'])
                pointer_bytes=8 if machine==0x8664 else 4
                assert p['ownership_protocol']==dict(pair_object_offset=0,pair_control_offset=pointer_bytes,
                    control_strong_offset=pointer_bytes,control_weak_offset=pointer_bytes+4,
                    destroy_virtual_slot=1,delete_virtual_slot=2)
            width = 8 if machine == 0x8664 else 4
            image_size = p['image_size']
            label = json.dumps(p['label'],ensure_ascii=True)
            output += ['{\n',f'    BuildId::{build}, L{label}, {p["file_size"]},\n',
                f'    Sha256Literal("{digest}"), 0x{image_size:X},\n','    {{\n']
            for hook in p['hooks']:
                output.append('        '+hook_literal(hook,image_size,width)+',\n')
            filename = f'L{json.dumps(config)}' if config else 'nullptr'
            vtable = p.get('pc_device_vtable_rva',0)
            release,lookup = p.get('release_control'),p.get('pc_device_lookup')
            device_id = p.get('pc_device_id',1)
            if backend == 'NuFileDeviceShared64':
                assert release and lookup and 0 < vtable < image_size and device_id == 1
            elif backend == 'NuFileExtendedShared':
                assert not release and lookup and 0 < vtable < image_size and device_id == 1
            elif backend == 'NttFile64':
                assert machine == 0x8664 and not release and lookup and not config
                assert digest == '10f0e68dc406af43a73ea0b59571d7d86f5c741b63cc3f1a6d2e45b0d581b22b'
                assert 0 < vtable < image_size and p['ntt_dat_device_vtable_rva'] > 0
                assert p['ntt_pc_file_vtable_rva'] > 0 and len(p['ntt_dat_hooks']) == 2
                assert all(p['ntt_dat_hooks'])
            else:
                assert not release and not lookup and not vtable
            output += ['    }},\n',f'    RedirectorBackend::{backend}, {filename}, 0x{machine:X}, 0x{vtable:X},\n',
                '    '+hook_literal(release,image_size,width)+',\n',
                '    '+hook_literal(lookup,image_size,width)+f', {device_id}, 0x{p["preferred_image_base"]:X}ULL, '+('true' if p.get('preferred_base_only',False) else 'false')]
            if backend == 'NttFile64':
                output += [',\n    {{'+', '.join(hook_literal(h,image_size,width) for h in p['ntt_dat_hooks'])+'}},\n',
                    f'    0x{p["ntt_dat_device_vtable_rva"]:X}, 0x{p["ntt_pc_file_vtable_rva"]:X}']
            else:
                assert not p.get('ntt_dat_hooks') and not p.get('ntt_dat_device_vtable_rva') and not p.get('ntt_pc_file_vtable_rva')
            output += ['\n','},\n']
    assert len(hashes) == len(profiles)
    output += ['#else\n#error Unsupported target architecture\n#endif\n']
    return ''.join(output)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    profiles = json.loads((ROOT/'profiles.json').read_text(encoding='utf-8'))
    generated = render(profiles)
    destination = ROOT/'src/generated_profiles.inc'
    if args.check:
        assert destination.read_text(encoding='utf-8') == generated,'Regenerate native profiles'
        print(f'{len(profiles)} compiled x86/x64 profiles match profiles.json')
    else:
        destination.write_text(generated,encoding='utf-8')
